import 'dart:async';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'app.dart';
import 'core/constants.dart';
import 'state/auth_state.dart';
import 'state/ligand_list_state.dart';
import 'state/ligand_detail_state.dart';

// we create our 3 state objects that we need and the root widget of our app and we share these 3 states to the app object and its widgets
// AuthState to check if someone logged in (read by the login screen)
// LigandListState to help with the filtering logic in our protein list screen 
// LigandDetailState to wrap the protein 3d screen of the ligand being opened, and how loading is going = success, error, loading
void main() {
  _keepNativeSplashOnScreen();
  runApp(
    MultiProvider( // MultiProvider is a widget that makes the 3 state objects available to every child widget (inside the app)
      providers: [ // we create 3 global instances of the app's states, and we share it with every widget in the app (so we have 1 global state for eveyrthing, not every widget has a differnent state object) = ChangeNotifierProvider also tells the screens that a value has changed in the states
        ChangeNotifierProvider(create: (_) => AuthState()), // we create a "AuthSTate" object and make it available to access by the widgets inside the child "SwiftyProteinApp" widget 
        ChangeNotifierProvider(create: (_) => LigandListState()),
        ChangeNotifierProvider(create: (_) => LigandDetailState()),
      ],
      child: const SwiftyProteinApp(), // we call the constructor of the root widget of our app (this gets built at start) = it calls the "build" method inside "app.dart"
    ),
  );
}

// The native splash (white + logo, generated by flutter_native_splash from pubspec.yaml) stays on screen until Flutter sends its first frame :
// holding that first frame back keeps the splash up, then the login screen appears. The app is still built behind the splash meanwhile, just not shown
// The 2 seconds start when our Dart code starts : the engine boots before that, so the splash is on screen slightly longer in total
// (flutter_native_splash's own preserve() / remove() do exactly this, but would need the package moved out of dev_dependencies)
void _keepNativeSplashOnScreen() {
  final binding = WidgetsFlutterBinding.ensureInitialized(); // Flutter's link to the engine : it must exist before we can hold a frame back (runApp reuses it)
  binding.deferFirstFrame();
  Timer(AppConstants.splashDuration, binding.allowFirstFrame);
}
